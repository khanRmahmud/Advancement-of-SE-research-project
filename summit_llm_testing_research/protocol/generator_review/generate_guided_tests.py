
#!/usr/bin/env python3

"""
METHOD B: SPECIFICATION-GUIDED LLM UNIT TEST GENERATION

Input:
    1. Summit TypeScript implementation.
    2. Independent software requirements.

Output:
    TypeScript unit tests generated by GPT.

Default:
    Dry run without API requests.
"""

from __future__ import annotations

import argparse
import json

from llm_common import (
    DEFAULT_MODEL,
    SUMMIT_ROOT,
    build_common_prompt,
    generate_test_code,
    read_source,
    read_spec,
    save_prompt,
    sha256_text,
    verify_target,
    write_metadata,
)


# ============================================================
# 1. Default experiment settings
# ============================================================

DEFAULT_SOURCE = (
    "summit/app/server/src/posts/posts.service.ts"
)

DEFAULT_SPEC = (
    "specifications/remove_post_requirements.json"
)

DEFAULT_TARGET = "removePostService"


# ============================================================
# 2. Main program
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--source",
        default=DEFAULT_SOURCE
    )

    parser.add_argument(
        "--spec",
        default=DEFAULT_SPEC
    )

    parser.add_argument(
        "--target",
        default=DEFAULT_TARGET
    )

    parser.add_argument(
        "--count",
        type=int,
        default=8
    )

    parser.add_argument(
        "--trial",
        type=int,
        default=2
    )

    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL
    )

    parser.add_argument(
        "--send",
        action="store_true"
    )

    args = parser.parse_args()

    if args.trial < 1 or args.count < 1:
        parser.error(
            "--trial and --count must be positive"
        )


    # ========================================================
    # 3. Read Summit implementation
    # ========================================================

    source, code = read_source(args.source)

    verify_target(
        code,
        args.target
    )


    # ========================================================
    # 4. Read independently reviewed specifications
    # ========================================================

    spec = read_spec(args.spec)

    if spec.get("target_function") != args.target:
        raise ValueError(
            "Specification target_function "
            "does not match --target"
        )

    actual_module = source.relative_to(
        SUMMIT_ROOT.resolve()
    ).as_posix()

    if spec.get("target_module") != actual_module:
        raise ValueError(
            f"Specification target_module must equal "
            f"{actual_module}"
        )


    # ========================================================
    # 5. Build IDENTICAL common prompt
    # ========================================================

    common = build_common_prompt(
        code=code,
        import_path=f"./{source.stem}.js",
        count=args.count,
        target_function=args.target
    )


    # ========================================================
    # 6. Append independent specifications
    # ========================================================

    spec_text = json.dumps(
        spec,
        indent=2,
        ensure_ascii=False
    )

    prompt = (
        common
        + "\nINDEPENDENT SOFTWARE SPECIFICATION "
        "(expected behavior):\n"
        + spec_text
        + "\n"
    )


    # ========================================================
    # 7. Define output file
    # ========================================================

    output = source.with_name(
        f"{source.stem}.guided.r{args.trial:02d}.test.ts"
    )

    if args.send and output.exists():
        raise FileExistsError(
            f"Refusing to overwrite test result: {output}"
        )


    # ========================================================
    # 8. Save guided prompt
    # ========================================================

    prompt_path = save_prompt(
        prompt=prompt,
        method="guided",
        trial=args.trial,
        source_name=source.stem
    )

    print("\n====================================")
    print("SPECIFICATION-GUIDED LLM GENERATION")
    print("====================================")

    print(f"\nSource: {source}")
    print(f"Target function: {args.target}")

    print(f"Source SHA-256: {sha256_text(code)}")
    print(f"Specification SHA-256: {sha256_text(spec_text)}")

    print(f"Prompt saved: {prompt_path}")


    # ========================================================
    # 9. Dry-run mode
    # ========================================================

    if not args.send:

        print("\nDRY RUN COMPLETED")
        print("No GPT API request.")
        print("No API charge.")
        print("No test code generated.")

        return


    # ========================================================
    # 10. Generate tests using GPT
    # ========================================================

    tests, info = generate_test_code(
        prompt=prompt,
        model=args.model
    )


    # ========================================================
    # 11. Save generated TypeScript tests
    # ========================================================

    output.write_text(
        tests,
        encoding="utf-8"
    )

    log_copy = (
        prompt_path.parent
        / "generated.guided.test.ts"
    )

    log_copy.write_text(
        tests,
        encoding="utf-8"
    )


    # ========================================================
    # 12. Save experimental metadata
    # ========================================================

    write_metadata(
        prompt_path.parent / "metadata.guided.json",
        {
            "arm": "guided",
            "target_function": args.target,
            "trial": args.trial,
            "requested_tests": args.count,
            "framework": "node:test",
            "source": str(source),
            "source_sha256": sha256_text(code),
            "specification_file": args.spec,
            "specification_sha256": sha256_text(spec_text),
            "prompt_file": str(prompt_path),
            "test_file": str(output),
            "test_file_sha256": sha256_text(tests),
            **info,
        }
    )

    print(f"\nGenerated tests saved: {output}")

    print(
        "Record initial test compilation and execution "
        "results before correcting generated tests."
    )


# ============================================================
# Program entry point
# ============================================================

if __name__ == "__main__":
    main()
