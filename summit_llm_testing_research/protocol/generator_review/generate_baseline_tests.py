
#!/usr/bin/env python3

"""
METHOD A: BASELINE LLM UNIT TEST GENERATION

Input:
    Summit TypeScript implementation only.

Output:
    TypeScript unit tests generated by GPT.

Default:
    Dry run without API requests.
"""

from __future__ import annotations

import argparse

from llm_common import (
    DEFAULT_MODEL,
    build_common_prompt,
    generate_test_code,
    read_source,
    save_prompt,
    sha256_text,
    verify_target,
    write_metadata,
)


# ============================================================
# 1. Default experiment settings
# ============================================================

DEFAULT_SOURCE = (
    "summit/app/server/src/posts/posts.service.ts"
)

DEFAULT_TARGET = "removePostService"


# ============================================================
# 2. Main program
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description=__doc__
    )

    parser.add_argument(
        "--source",
        default=DEFAULT_SOURCE
    )

    parser.add_argument(
        "--target",
        default=DEFAULT_TARGET
    )

    parser.add_argument(
        "--count",
        type=int,
        default=8
    )

    parser.add_argument(
        "--trial",
        type=int,
        default=2
    )

    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL
    )

    parser.add_argument(
        "--send",
        action="store_true"
    )

    args = parser.parse_args()

    if args.trial < 1 or args.count < 1:
        parser.error(
            "--trial and --count must be positive"
        )


    # ========================================================
    # 3. Read Summit TypeScript implementation
    # ========================================================

    source, code = read_source(args.source)

    verify_target(
        code,
        args.target
    )


    # ========================================================
    # 4. Construct baseline prompt
    # ========================================================

    prompt = build_common_prompt(
        code=code,
        import_path=f"./{source.stem}.js",
        count=args.count,
        target_function=args.target
    )


    # ========================================================
    # 5. Define output file
    # ========================================================

    output = source.with_name(
        f"{source.stem}.baseline.r{args.trial:02d}.test.ts"
    )

    if args.send and output.exists():
        raise FileExistsError(
            f"Refusing to overwrite test result: {output}"
        )


    # ========================================================
    # 6. Save the baseline prompt
    # ========================================================

    prompt_path = save_prompt(
        prompt=prompt,
        method="baseline",
        trial=args.trial,
        source_name=source.stem
    )

    print("\n====================================")
    print("BASELINE: CODE-ONLY LLM GENERATION")
    print("====================================")

    print(f"\nSource: {source}")
    print(f"Target function: {args.target}")
    print(f"Source SHA-256: {sha256_text(code)}")
    print(f"Prompt saved: {prompt_path}")


    # ========================================================
    # 7. Dry-run mode
    # ========================================================

    if not args.send:

        print("\nDRY RUN COMPLETED")
        print("No GPT API request.")
        print("No API charge.")
        print("No test code generated.")

        return


    # ========================================================
    # 8. Generate tests using GPT
    # ========================================================

    tests, info = generate_test_code(
        prompt=prompt,
        model=args.model
    )


    # ========================================================
    # 9. Save generated TypeScript tests
    # ========================================================

    output.write_text(
        tests,
        encoding="utf-8"
    )

    log_copy = (
        prompt_path.parent
        / "generated.baseline.test.ts"
    )

    log_copy.write_text(
        tests,
        encoding="utf-8"
    )


    # ========================================================
    # 10. Save experimental metadata
    # ========================================================

    write_metadata(
        prompt_path.parent / "metadata.baseline.json",
        {
            "arm": "baseline",
            "target_function": args.target,
            "trial": args.trial,
            "requested_tests": args.count,
            "framework": "node:test",
            "source": str(source),
            "source_sha256": sha256_text(code),
            "prompt_file": str(prompt_path),
            "test_file": str(output),
            "test_file_sha256": sha256_text(tests),
            **info,
        }
    )

    print(f"\nGenerated tests saved: {output}")

    print(
        "Record initial test compilation and execution "
        "results before correcting generated tests."
    )


# ============================================================
# Program entry point
# ============================================================

if __name__ == "__main__":
    main()
